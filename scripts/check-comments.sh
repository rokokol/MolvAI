# duplicate-doc is the one rule that reads two files at once, so it is its own pass. It
# counts three-word runs shared between a comment block and one entry of a maintainer
# document: a correct pointer shares the entry's terms and none of its phrases, which is
# the measurement that told phrases from terms in the first place
if [[ -s "$work/entries" ]]; then
  awk -F'\t' -v ROOT="$root/" '
    function rel(p) { sub("^" ROOT, "", p); return p }
    function norm(s) {
      gsub(/`/, " ", s); s = tolower(s)
      gsub(/[^a-z0-9 ]/, " ", s); gsub(/  +/, " ", s)
      return s
    }
    function trigrams(s, bag,   n, w, i, key, made) {
      n = split(norm(s), w, " "); made = 0
      for (i = 1; i + 2 <= n; i++) {
        key = w[i] " " w[i+1] " " w[i+2]
        if (!(key in bag)) { bag[key] = 1; made++ }
      }
      return made
    }
    # A double-quoted span is a citation, and the form this rule asks for cites the entry
    # by its heading. Counting those words would charge a correct pointer for the one thing
    # that makes it correct
    function spoken(s,   out, i, ch, inq) {
      out = ""; inq = 0
      for (i = 1; i <= length(s); i++) {
        ch = substr(s, i, 1)
        if (ch == "\"") { inq = !inq; continue }
        if (!inq) out = out ch
      }
      return out
    }
    NR == FNR {
      if ($1 == "C" && $5 == "own") {
        key = $2 "\t" $4
        body[key] = body[key] " " $12
        if (!(key in first)) first[key] = $3
      }
      next
    }
    { entry[$1 "\t" $2] = entry[$1 "\t" $2] " " $3 }
    END {
      for (key in body) {
        n = trigrams(spoken(body[key]), mine)
        if (n < 5) { delete mine; continue }
        for (e in entry) {
          delete theirs
          # The share is of the entry, not of the comment. A comment measured against
          # itself is charged for being short: a pointer that states the one fact its line
          # needs has few runs of its own, so the handful it must share with the entry —
          # the names, the setting, the path — is a large part of it. Shortening a correct
          # pointer here from four lines to two moved it from 16 per cent to 20. Measured
          # against the entry the question is the one the rule asks: how much of what the
          # entry says has been said again
          theirn = trigrams(entry[e], theirs)
          if (theirn < 5) continue
          shared = 0; examples = ""
          for (t in mine)
            if (t in theirs) {
              shared++
              if (shared <= 3) examples = examples (examples ? ", " : "") "\"" t "\""
            }
          # Two ways to be a retelling, because one measure alone is wrong in one direction
          # each. A sentence of fifteen words holds thirteen three-word runs, so a dozen
          # said again is a sentence copied, however long the entry it came from. And a
          # sixth of a short entry is that entry told twice even where the count is smaller
          if (shared >= 12 || (shared >= 5 && shared * 100 >= theirn * 15)) {
            split(key, k, "\t"); split(e, ee, "\t")
            printf "warning\t%s\t%s\tduplicate-doc\t%s\n", rel(k[1]), first[key],
              "says " shared " of the " theirn " three-word runs (" int(shared * 100 / theirn) "%) of " ee[1] " \"" ee[2] "\" again: " examples " — point at the entry instead of restating it"
            break
          }
        }
        delete mine
      }
    }
  ' "$work/facts" "$work/entries" >>"$work/findings"
fi

# The excuses are applied here, once, so no rule has to remember them — and an excuse that
# matched nothing is itself a finding
: >"$work/used"
kept=0
errors=0
warnings=0
while IFS=$'\t' read -r tier file line id what; do
  [[ -n "$id" ]] || continue
  excused=""
  while read -r aid apath atext; do
    [[ "$aid" == "$id" ]] || continue
    if [[ "$apath" == */ ]]; then
      [[ "$file" == "$apath"* ]] || continue
    else
      [[ "$file" == "$apath" ]] || continue
    fi
    if [[ -n "$atext" ]]; then
      grep -q -- "$atext" <<<"$what" || {
        # the text narrows by the source line, not by the message
        grep -q -- "$atext" <<<"$(sed -n "${line}p" "$root/$file" 2>/dev/null)" || continue
      }
    fi
    excused=1
    printf '%s\t%s\t%s\n' "$aid" "$apath" "$atext" >>"$work/used"
    break
  done <"$work/allow"
  [[ -z "$excused" ]] || continue
  kept=$((kept + 1))
  if [[ "$tier" == error ]]; then
    errors=$((errors + 1))
    printf 'check-comments: %s:%s: %s: %s\n' "$file" "$line" "$id" "$what" >&2
  else
    warnings=$((warnings + 1))
    printf 'check-comments: warning: %s:%s: %s: %s\n' "$file" "$line" "$id" "$what"
    [[ -z "${GITHUB_ACTIONS:-}" ]] ||
      printf '::warning file=%s,line=%s::%s: %s\n' "$file" "$line" "$id" "$what"
    [[ -z "$strict" ]] ||
      printf 'check-comments: %s:%s: %s: %s (under --strict)\n' "$file" "$line" "$id" "$what" >&2
  fi
done <"$work/findings"

stale=0
while read -r aid apath atext; do
  [[ -n "$aid" ]] || continue
  grep -qxF "$(printf '%s\t%s\t%s' "$aid" "$apath" "$atext")" "$work/used" 2>/dev/null && continue
  printf 'check-comments: check-comments.allow: the entry for %s %s %s excuses nothing — remove it\n' \
    "$aid" "$apath" "$atext" >&2
  stale=$((stale + 1))
done <"$work/allow"

printf 'check-comments: %s comment lines in %s files, %s errors, %s warnings\n' \
  "$(awk -F'\t' '$1 == "C"' "$work/facts" | wc -l | tr -d ' ')" \
  "$(wc -l <"$work/files" | tr -d ' ')" "$errors" "$warnings"

((errors == 0 && stale == 0)) || exit 1
[[ -z "$strict" ]] || ((warnings == 0)) || exit 1
exit 0
