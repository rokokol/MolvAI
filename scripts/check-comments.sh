    # An empty comment line ends a paragraph, and so a sentence: joining across one welds
    # the last words of a paragraph to the first of the next and reports the pair as one
    function flush(   i, n, parts, sentence, words, w, count, j) {
      if (body == "") return
      n = split(body, parts, /[.?;] +/)
      for (i = 1; i <= n; i++) {
        sentence = parts[i]
        count = 0
        w = split(sentence, words, /[ \t]+/)
